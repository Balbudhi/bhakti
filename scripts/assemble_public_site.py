#!/usr/bin/env python3
"""Assemble the shared public Pages allowlist; never copy pipeline/review state."""
from __future__ import annotations

from contextlib import ExitStack
import base64
import hashlib
import json
import re
from urllib.parse import urlsplit, urljoin
from pathlib import Path
import shutil
import tempfile
import bhakti_shuffle_profiles as shuffle_profiles

from bhakti_boundary_timebase import (boundary_transaction, boundary_snapshot,
    require_boundary_snapshot, require_completed_boundary_transaction)

ROOT = Path(__file__).resolve().parents[1]
PUBLIC_ROOT_FILES = ('index.html', 'manifest.webmanifest', 'sw.js', 'robots.txt', 'sitemap.xml', 'CNAME')



def revision_url(path: str, content: bytes) -> str:
    return path + '?v=' + hashlib.sha256(content).hexdigest()


def prepare_release(staged: Path) -> None:
    """Bind generated entrypoints and worker to this validated public snapshot.

    Source readers remain untouched. The release map owns URLs used by dynamic
    loaders; the worker owns verified caching, never listener audio.
    """
    resource_paths = sorted(path for path in staged.rglob('*') if path.is_file()
        and (path.relative_to(staged).parts[0] == 'assets'
             or path.name == 'data.js' or path.relative_to(staged).as_posix() in
             {'data/songs.js', 'data/shuffle-profiles.js', 'manifest.webmanifest'}))
    if (staged / 'assets/release-map.js').exists():
        raise RuntimeError('release-map.js is generated by public assembly')
    urls = {'/' + path.relative_to(staged).as_posix(): revision_url(
        '/' + path.relative_to(staged).as_posix(), path.read_bytes()) for path in resource_paths}
    # Fonts/images are revisioned before CSS, so CSS itself has one stable hash.
    for path in resource_paths:
        if path.suffix != '.css':
            continue
        relative = '/' + path.relative_to(staged).as_posix()
        def css_url(match):
            raw = match[2]
            parsed = urlsplit(urljoin(relative, raw))
            if parsed.scheme or parsed.netloc or parsed.path not in urls:
                return match[0]
            if Path(parsed.path).suffix == '.css':
                raise RuntimeError('CSS imports need explicit dependency ordering')
            return 'url(' + match[1] + urls[parsed.path] + ('#' + parsed.fragment if parsed.fragment else '') + match[1] + ')'
        text = re.sub(r"url\(\s*(['\"]?)([^)'\"\s]+)\1\s*\)", css_url, path.read_text())
        path.write_text(text)
        urls[relative] = revision_url(relative, path.read_bytes())
    release_map = staged / 'assets/release-map.js'
    release_map.parent.mkdir(exist_ok=True)
    release_map.write_text('window.BHAKTI_ASSETS = Object.freeze(' +
        json.dumps(urls, ensure_ascii=True, separators=(',', ':')) + ');\n')
    urls['/assets/release-map.js'] = revision_url('/assets/release-map.js', release_map.read_bytes())

    for page in [staged / 'index.html', *sorted((staged / 'songs').glob('*/index.html'))]:
        html = page.read_text()
        # Historical source documents retain their reviewed identities. Apply
        # runtime adoption only to the independently validated deployment copy.
        html = re.sub(r'<script\b[^>]*src=["\'](?:/assets/shuffle\.js|/data/shuffle-profiles\.js)(?:\?[^"\']*)?["\'][^>]*>\s*</script>\s*', '', html)
        html = re.sub(r'<link\b[^>]*(?:https://fonts\.googleapis\.com|https://fonts\.gstatic\.com)[^>]*>\s*', '', html)
        if '/assets/fonts.css' in urls and not re.search(r'href=["\']/assets/fonts\.css', html):
            html = html.replace('</head>', '<link rel="stylesheet" href="/assets/fonts.css">\n</head>')
        if '/assets/shuffle-client.js' in urls and not re.search(r'src=["\']/assets/shuffle-client\.js', html):
            html = re.sub(r'(?=<script\b[^>]*src=["\']/assets/app\.js)',
                          '<script src="/assets/shuffle-client.js"></script>\n', html, count=1)
        html = re.sub(r'(?=<script\b)', '<script src="/assets/release-map.js"></script>\n', html, count=1)
        relative = '/' + page.relative_to(staged).as_posix()
        def html_url(match):
            parsed = urlsplit(urljoin(relative, match[3]))
            if parsed.scheme or parsed.netloc or parsed.path not in urls:
                return match[0]
            return match[1] + match[2] + urls[parsed.path] + ('#' + parsed.fragment if parsed.fragment else '') + match[2]
        html = re.sub(r'((?:src|href)=)(["\'])([^"\']+)\2', html_url, html)
        def integrity_tag(match):
            tag = match[0]
            if tag.startswith('<link') and not re.search(r'rel=["\']stylesheet["\']', tag):
                return tag
            reference = re.search(r'(?:src|href)=["\']([^"\']+)', tag)
            if not reference:
                return tag
            parsed = urlsplit(reference[1])
            if parsed.scheme or parsed.netloc or parsed.path not in urls:
                return tag
            digest = urls[parsed.path].rsplit('=', 1)[1]
            integrity = 'sha256-' + base64.b64encode(bytes.fromhex(digest)).decode()
            tag = re.sub(r'\s+integrity=["\'][^"\']*["\']', '', tag)
            return tag[:-1] + ' integrity="' + integrity + '">'
        # An uncontrolled first visit also rejects a deployment-race mixture;
        # hash-shaped query parameters alone do not authenticate server bytes.
        html = re.sub(r'<(?:script|link)\b[^>]*>', integrity_tag, html)
        page.write_text(html)

    documents = {'/' + path.relative_to(staged).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest()
                 for path in [staged / 'index.html', *sorted((staged / 'songs').glob('*/index.html'))]}
    # Precache the home entrypoint and its real dependencies, not every public
    # asset (including unused styles, license texts and deferred shuffle data).
    required = {'/assets/release-map.js', '/manifest.webmanifest', '/assets/icon-192.png',
                '/assets/media-session.js', '/assets/owner-entry.js', '/assets/player-icons.svg'}
    home = (staged / 'index.html').read_text()
    required.update(urlsplit(raw).path for raw in re.findall(r'(?:src|href)=["\']([^"\']+)', home)
                    if raw.startswith('/'))
    for path in list(required):
        if path in urls and path.endswith('.css'):
            required.update(urlsplit(raw).path for raw in re.findall(
                r'url\(["\']?([^\)"\']+)', (staged / path.lstrip('/')).read_text()))
    lazy = {'/assets/shuffle.js', '/assets/shuffle-worker.js', '/data/shuffle-profiles.js'}
    shell = ['/', *[url for path, url in urls.items()
                   if path in required and path not in lazy and not path.startswith('/songs/')]]
    release = hashlib.sha256(json.dumps([urls, documents,
        hashlib.sha256((staged / 'sw.js').read_bytes()).hexdigest()], sort_keys=True).encode()).hexdigest()[:20]
    config = {'release': release, 'paths': urls,
              'documents': documents, 'shell': shell}
    worker = staged / 'sw.js'
    worker.write_text('const BHAKTI_RELEASE = ' + json.dumps(config, separators=(',', ':')) + ';\n' + worker.read_text())

def assemble_public_site(root: Path) -> None:
    root = Path(root)
    songs = sorted((path for path in (root / 'songs').iterdir() if path.is_dir()), key=lambda path: str(path.resolve()))
    with ExitStack() as locks:
        for song in songs:
            locks.enter_context(boundary_transaction(song))
        _assemble_locked(root, songs)


def _assemble_locked(root: Path, songs: list[Path]) -> None:
    for song in songs:
        require_completed_boundary_transaction(song)
    profile_paths = [root / path for path in (shuffle_profiles.POLICY, shuffle_profiles.REVIEWS,
        shuffle_profiles.TAXONOMY, 'data/media.json') if (root / path).is_file()]
    profile_fingerprints = {path: hashlib.sha256(path.read_bytes()).hexdigest() for path in profile_paths}
    has_profiles = shuffle_profiles.enabled(root)
    files = [root / name for name in PUBLIC_ROOT_FILES]
    if has_profiles:
        files.append(root / shuffle_profiles.PUBLIC)
    files.append(root / 'data/songs.js')
    files.extend(path for path in (root / 'assets').rglob('*') if path.is_file())
    files.extend(song / name for song in songs for name in ('index.html', 'data.js') if (song / name).is_file())
    # Retain the deployment's internal-file check and reject symlinks rather
    # than following an apparently public path into private source material.
    for path in files:
        relative = path.relative_to(root)
        if (any((root / Path(*relative.parts[:index])).is_symlink() for index in range(1, len(relative.parts) + 1))
                or path.name in {'AGENTS.md', 'README.md', '.gitignore'}
                or path.suffix == '.py' or {'docs', 'scripts'} & set(relative.parts)):
            raise RuntimeError(f'internal or linked file in public allowlist: {relative}')
    snapshots = {song: boundary_snapshot(song, [song / 'index.html', song / 'data.js']) for song in songs}
    fingerprints = {path: hashlib.sha256(path.read_bytes()).hexdigest() for path in files}
    # Bind the public bytes BEFORE validation; a direct writer may ignore locks.
    shuffle_profiles.validate_public_profiles(root, required=False)
    with tempfile.TemporaryDirectory(prefix='.public-site-', dir=root) as temporary:
        staged = Path(temporary) / 'site'
        staged.mkdir()
        for source in files:
            destination = staged / source.relative_to(root)
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, destination)
        # Validate the copied snapshot as well as current inputs. A completed
        # old→new transition can evade a pending-only check but not this binding.
        current = sorted((path for path in (root / 'songs').iterdir() if path.is_dir()), key=lambda path: str(path.resolve()))
        if current != songs:
            raise RuntimeError('public assembly song population changed')
        for song, snapshot in snapshots.items():
            require_boundary_snapshot(song, snapshot)
        for path, fingerprint in profile_fingerprints.items():
            if not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != fingerprint:
                raise RuntimeError('shuffle assessment inputs changed during public assembly')
        for path, fingerprint in fingerprints.items():
            copied = staged / path.relative_to(root)
            if (hashlib.sha256(path.read_bytes()).hexdigest() != fingerprint
                    or hashlib.sha256(copied.read_bytes()).hexdigest() != fingerprint):
                raise RuntimeError('public assembly snapshot changed: ' + str(path.relative_to(root)))
        prepare_release(staged)
        destination = root / '_site'
        if destination.is_symlink():
            raise RuntimeError('public artifact destination must not be a symlink')
        if destination.exists():
            shutil.rmtree(destination)
        staged.replace(destination)


if __name__ == '__main__':
    assemble_public_site(ROOT)
